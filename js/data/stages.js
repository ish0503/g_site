// 진형 → 실제 좌표
SW.stageDeployment = (stage) => {
  const list = [];
  for (const [unit, count, cx, cy, cols] of stage.enemies) {
    const def = SW.UNITS[unit];
    const gap = def.size * 2 + 8;
    const rows = Math.ceil(count / cols);
    for (let i = 0; i < count; i++) {
      const c = i % cols, r = Math.floor(i / cols);
      list.push({ type: unit, team: 1, x: cx + (c - (cols - 1) / 2) * gap, y: cy + (r - (rows - 1) / 2) * gap });
    }
  }
  return list;
};
SW.stageEnemyPop = (stage) => stage.enemies.reduce((s, [u, n]) => s + SW.UNITS[u].pop * n, 0);
